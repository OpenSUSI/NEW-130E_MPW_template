#!/usr/bin/env python3
"""
Generic Gate-Level Verilog -> LVS Reference SPICE Netlist (.cir) Generator
for openroad_std PDKs (IHP SG13G2, SKY130, NEW-130E).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from config_loader import load_design_and_pdk


def parse_subckt_pins(spice_path: Path) -> dict[str, list[str]]:
    """Parse .subckt <name> <pin1> <pin2> ... (handling '+' continuation lines)."""
    raw_lines = spice_path.read_text(encoding="utf-8", errors="replace").splitlines()
    joined: list[str] = []
    for line in raw_lines:
        s = line.strip()
        if not s or s.startswith("*"):
            continue
        if s.startswith("+") and joined:
            joined[-1] += " " + s[1:].strip()
        else:
            joined.append(s)

    subckts: dict[str, list[str]] = {}
    for line in joined:
        if line.lower().startswith(".subckt "):
            toks = line.split()
            if len(toks) >= 2:
                name = toks[1]
                pins = [t for t in toks[2:] if "=" not in t]
                subckts[name] = pins
    return subckts


def parse_verilog_instances(v_path: Path, top_module: str) -> tuple[list[str], list[tuple[str, str, dict[str, str]]]]:
    text = v_path.read_text(encoding="utf-8", errors="replace")
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"//.*", "", text)

    m = re.search(rf"\bmodule\s+{re.escape(top_module)}\s*\((.*?)\)\s*;", text, flags=re.DOTALL)
    if not m:
        raise ValueError(f"Module '{top_module}' not found in {v_path}")
    ports = [p.strip() for p in m.group(1).split(",") if p.strip()]

    inst_re = re.compile(
        r"\b([A-Za-z_][A-Za-z0-9_$]*)\s+([A-Za-z_\\][A-Za-z0-9_$\[\]\.]*)\s*\((.*?)\)\s*;",
        flags=re.DOTALL,
    )
    skip_kw = {"module", "input", "output", "inout", "wire", "reg", "assign"}
    instances: list[tuple[str, str, dict[str, str]]] = []
    for im in inst_re.finditer(text):
        cell_type, inst_name, conn_blob = im.group(1), im.group(2), im.group(3)
        if cell_type in skip_kw:
            continue
        conns: dict[str, str] = {}
        for cm in re.finditer(r"\.([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*([^)]+?)\s*\)", conn_blob):
            conns[cm.group(1)] = cm.group(2).strip()
        if conns:
            instances.append((cell_type, inst_name.lstrip("\\"), conns))
    return ports, instances


def main() -> None:
    design, pdk = load_design_and_pdk(ROOT)
    top_module = design["design"]["top_module"]
    top_cell = design["design"]["top_cell"]

    views = pdk.get("views", {})
    stdcell_spice = views.get("stdcell_spice", "")
    pwr = pdk.get("padframe", {}).get("power_pads", {})
    vdd = pwr.get("vdd", "VDD")
    vss = pwr.get("vss", "VSS")

    syn_v = ROOT / f"output/work/{top_module}_syn.v"
    out_cir = ROOT / f"output/gds/{top_cell}.cir"

    ports, instances = parse_verilog_instances(syn_v, top_module)
    subckt_pins: dict[str, list[str]] = {}
    if stdcell_spice and (ROOT / stdcell_spice).is_file():
        subckt_pins = parse_subckt_pins(ROOT / stdcell_spice)

    pwr_names = {"VDD", "VPWR", "VPB", "vdd", "vpwr", "vpb"}
    gnd_names = {"VSS", "VGND", "VNB", "vss", "vgnd", "vnb"}

    lines = [
        f"* LVS Reference Netlist for {top_cell} (generated by scripts/openroad_v2spice.py)",
        f"* PDK: {pdk['name']}",
    ]
    if stdcell_spice and (ROOT / stdcell_spice).is_file():
        lines.append(f".include \"{(ROOT / stdcell_spice).resolve()}\"")
    lines.append("")
    lines.append(f".subckt {top_cell} " + " ".join(ports + [vdd, vss]))

    for idx, (cell_type, inst_name, conns) in enumerate(instances):
        safe_inst = re.sub(r"[^A-Za-z0-9_]", "_", inst_name)
        pin_order = subckt_pins.get(cell_type)
        if pin_order:
            nets = []
            for p in pin_order:
                if p in conns:
                    nets.append(conns[p])
                elif p in pwr_names:
                    nets.append(vdd)
                elif p in gnd_names:
                    nets.append(vss)
                else:
                    nets.append(f"unconn_{idx}_{p}")
        else:
            nets = [conns[k] for k in sorted(conns)] + [vdd, vss]
        lines.append(f"X{safe_inst} " + " ".join(nets) + f" {cell_type}")

    lines.append(f".ends {top_cell}")
    lines.append(".end")

    out_cir.parent.mkdir(parents=True, exist_ok=True)
    out_cir.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote LVS SPICE: {out_cir.relative_to(ROOT)} ({len(instances)} instances)")


if __name__ == "__main__":
    main()
